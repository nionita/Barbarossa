#!/usr/bin/env python3
"""Generate Struct.Pst (the compiled piece square table) from a config file with pst.* lines.

The config lines are pst.mid.<piece><square> = value and pst.end.<piece><square> = value (piece one of
PNBRQK, square a1 .. h8, values in 1/8 centipawns, owner's view), as written by hv_cfg.py of
BarbarossaTuning. Missing entries are 0, other lines (weights) are ignored. The module contains the
384 (mid, end) pairs in the order piece (PNBRQK) * 64 + square (a1 = 0 .. h8 = 63).

With --base MODULE the values of an existing Struct.Pst module are added: a fitted candidate config
(hv_cfg.py) holds the PST corrections on top of the compiled table, so the new compiled table is
base + corrections.

Examples:
    python scripts/config_to_pst.py C:/Learn/Tune/hvar/cand/sp-both.cfg Struct/Pst.hs
    python scripts/config_to_pst.py --base Struct/Pst.hs C:/Learn/Tune/hvar/cand/r2-both.cfg Struct/Pst.hs
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PIECES = "PNBRQK"
PST_RE = re.compile(r"^\s*pst\.(mid|end)\.([PNBRQK])([a-h])([1-8])\s*=\s*(-?[0-9.eE+-]+)\s*$")


def parse_config(path: Path) -> list[list[int]]:
    table = [[0, 0] for _ in range(6 * 64)]
    for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip().startswith("pst."):
            continue
        m = PST_RE.match(line)
        if not m:
            raise ValueError(f"line {line_no}: wrong PST line: {line.strip()}")
        phase, piece, file, rank, value = m.groups()
        idx = PIECES.index(piece) * 64 + (int(rank) - 1) * 8 + "abcdefgh".index(file)
        table[idx][0 if phase == "mid" else 1] = int(round(float(value)))
    return table


def parse_module(path: Path) -> list[list[int]]:
    """The (mid, end) pairs of a generated Struct.Pst module."""
    text = path.read_text(encoding="utf-8").split("pstValues = [", 1)[1]
    pairs = re.findall(r"\((-?\d+), (-?\d+)\)", text)
    if len(pairs) != 6 * 64:
        raise ValueError(f"{path}: expected {6 * 64} PST pairs, found {len(pairs)}")
    return [[int(m), int(e)] for m, e in pairs]


def render_module(table: list[list[int]], source: str) -> str:
    lines = [
        "-- This module is generated by scripts/config_to_pst.py and contains only the",
        "-- piece square table values (1/8 centipawns, owner's view: black pieces use the",
        "-- vertically mirrored square), in the order piece (PNBRQK) * 64 + square (a1 = 0)",
        f"-- Source: {source}",
        "",
        "module Struct.Pst (",
        "    pstValues,",
        ") where",
        "",
        "-- (mid, end) per piece and square",
        "pstValues :: [(Int, Int)]",
        "pstValues = [",
    ]
    for t, piece in enumerate(PIECES):
        for rank in range(8):
            row = table[t * 64 + rank * 8: t * 64 + rank * 8 + 8]
            first = t == 0 and rank == 0
            cells = ", ".join(f"({m}, {e})" for m, e in row)
            lines.append(f"        {' ' if first else ','} {cells}\t-- {piece} rank {rank + 1}")
    lines.append("    ]")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", type=Path, help="Input config file with pst.* lines")
    parser.add_argument("output", type=Path, help="Output Haskell module path (Struct/Pst.hs)")
    parser.add_argument("--base", type=Path, help="Struct.Pst module whose values are added")
    args = parser.parse_args()
    table = parse_config(args.input)
    source = args.input.as_posix()
    if args.base:
        base = parse_module(args.base)
        table = [[m + bm, e + be] for (m, e), (bm, be) in zip(table, base)]
        source = f"{source} (corrections) + previous {args.base.as_posix()}"
    nonzero = sum(1 for m, e in table if m or e)
    args.output.write_text(render_module(table, source), encoding="utf-8", newline="\n")
    print(f"{args.output}: {nonzero} non zero entries of {len(table)}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
